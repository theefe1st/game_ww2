const natI = (S, n) => S.M.nats.indexOf(n);
// переходы областей события
function applyOwn(S, E) {
  if (E.own) for (const [nat, names] of Object.entries(E.own)) {
    const k = natI(S, nat);
    for (const n of names.split(' ')) { const r = regByName(S, n); if (r >= 0 && k >= 0 && S.own[r] !== k) { S.own[r] = k; S.capT[r] = S.turn; } }
  }
  if (E.join && S.out) for (const n of E.join) if (S.out[n] === 2) delete S.out[n];
}
// ближайшая своя область с местом (поиск в ширину по всем областям)
function nearOwn(S, side, r0) {
  const M = S.M, seen = new Uint8Array(M.R), q = [r0];
  seen[r0] = 1;
  for (let h = 0; h < q.length; h++) {
    const r = q[h];
    if (r !== r0 && sideOf(S, r) === side && room(S, r, side) > 0) return r;
    for (const e of M.reg[r].nb) if (!seen[e.r]) { seen[e.r] = 1; q.push(e.r); }
  }
  return -1;
}
// дивизии на чужой (теперь) земле — в ближайшую свою область
export function fixUnits(S) {
  for (const u of S.units) {
    if (!alive(u) || sideOf(S, u.r) === u.s) continue;
    const a = S.at[u.r];
    a.splice(a.indexOf(u), 1);
    const r = nearOwn(S, u.s, u.r);
    if (r < 0) { u.at = u.r; u.r = -1; u.arr = S.turn + 1; continue; }
    u.r = r; S.at[r].push(u); u.mp = 0; u.ent = 0;
  }
}
// границы 1936 г. и события до даты старта (без карточек и без действий — их итог уже в состоянии 1941 г.)
export function setBorders(S, iso) {
  S.out ??= {};
  for (const n of OUT_PW) S.out[n] = 2;
  for (const [nat, names] of Object.entries(B36)) {
    const k = natI(S, nat);
    for (const n of names.split(' ')) { const r = regByName(S, n); if (r >= 0) S.own[r] = k; }
  }
  S.pev ??= {};
  for (const E of PREWAR) if (E.at < iso) { applyOwn(S, E); S.pev[E.id] = -999; }
}
// события мирного времени (из runEvents): карточки — как у событий войны
export function runPrewar(S) {
  if (!S.pev) return;
  let ch = 0;
  for (const E of PREWAR) {
    if (S.pev[E.id] !== undefined || S.turn < T(E.at)) continue;
    S.pev[E.id] = S.turn;
    applyOwn(S, E);
    if (E.own) ch = 1;
    E.fx?.(S);
    S.evq.push({ id: E.id, t: S.turn, ask: 0 });
    note(S, { ic: E.ic, side: E.side === 'both' ? S.side : E.side, txt: E.t, ev: E.id });
  }
  if (ch) { reindex(S); fixUnits(S); }
}
// ★, люди и запасы мирного времени — до предела
export function peaceCaps(S, side) {
  S.men[side] = Math.min(S.men[side], PEACE_MEN[side]);
  S.pol[side] = Math.min(S.pol[side], PEACE_POL);
  const q = S.eq[side], q0 = S.eqStd?.[side];
  if (q0) for (const c in q) q[c] = Math.min(q[c], q0[c] * PEACE_EQ);
}
// начало войны (endWeek, ход 0): союзники вступают в войну; ИИ — в расстановку и запасы 22.06.1941;
// внезапность — у СССР (если не принято решение «Боевая готовность»)
const STD_MOR = { GER: 75, SOV: 60, men: { GER: 60, SOV: 150 } };
export function warStart(S) {
  S.peace = 0;
  if (S.out) for (const n in S.out) if (S.out[n] === 2) delete S.out[n];
  reindex(S);
  fixUnits(S);
  const ai = (sd) => sd !== S.side || (S.noAsk && !S.plSim);
  for (const sd of ['GER', 'SOV']) {
    if (!ai(sd)) {
      // игрок: боевой дух — как 22.06.1941 с поправкой на события мирного времени
      S.mor[sd] = Math.max(20, Math.min(100, STD_MOR[sd] + S.mor[sd] - lerpT(MOR0[sd], yearF(S.turn))));
      // войска в странах-союзниках (Финляндия, Румыния) — на места по плану: переброшены по договорам до 22 июня
      for (const u of S.units) {
        if (u.s !== sd || !alive(u) || u.hp === undefined || u.r < 0 || u.r === u.hp || S.M.nats[S.own[u.hp]] === sd || sideOf(S, u.hp) !== sd || room(S, u.hp, sd) <= 0) continue;
        const a = S.at[u.r]; a.splice(a.indexOf(u), 1); u.r = u.hp; S.at[u.hp].push(u); u.mp = 0; u.ent = 0;
      }
      continue;
    }
    for (const u of S.units) {
      if (u.s !== sd || u.dead || u.hp === undefined || (u.arr !== undefined && u.arr > S.turn && !u.pw)) continue;
      if (sideOf(S, u.hp) !== sd) continue;
      if (u.r >= 0) { const a = S.at[u.r]; a.splice(a.indexOf(u), 1); }
      u.r = u.hp; S.at[u.hp].push(u);
      delete u.arr; delete u.at; delete u.tr; delete u.camp;
      if (u.std) [u.str, u.rdy, u.xp] = u.std;
      u.ent = 0; u.oos = 0; u.mp = 0; u.mv = 0;
    }
    if (S.eqStd) S.eq[sd] = { ...S.eqStd[sd] };
    if (S.facStd) for (let r = 0; r < S.M.R; r++) if (S.M.nats[S.own0[r]] === sd) S.fac[r] = S.facStd[r];
    if (S.lineStd) { S.line[sd].sh = { ...S.lineStd[sd] }; for (const c in S.line[sd].e) S.line[sd].e[c] = 1; }
    S.men[sd] = STD_MOR.men[sd]; S.pol[sd] = 25; S.mor[sd] = STD_MOR[sd];
    if (S.airK) S.airK[sd] = 1;
    S.air[sd] = AIR0[sd];
    if (S.tech) { delete S.tech[sd]; ensureTech(S); } // наука — «по истории» (как у ИИ в обычной игре)
  }
  for (const u of S.units) delete u.std;
  delete S.facStd;
  initFleets(S); // флоты — как 22.06.1941 (кораблей до войны не строим)
  // внезапность: у границы — не в боевой готовности, окопы не заняты (кроме Финского направления — см. setup.js: placeArmy)
  if (!S.flags.SOVready) {
    const d = frontDist(S, 'SOV');
    for (const u of S.units) if (alive(u) && u.s === 'SOV' && d[u.r] <= 1 && S.M.reg[u.r].z !== 0) { u.rdy = Math.min(u.rdy, 45); u.ent = Math.min(u.ent, 1); }
  }
}
