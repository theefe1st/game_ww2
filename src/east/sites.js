// направление по точке и владельцу 1941 г.
export function zoneOf(lon, lat, nat) {
  if (nat === 'FIN') return 0;
  if (nat === 'GER' && lat > 63) return 0; // Северная Норвегия
  if (nat === 'SOV' && lon < 52 && (lat >= 60.6 || (lat >= 60.1 && lon < 30.6))) return 0; // Карелия, Кольский, Архангельск
  if (lat > lerp(B_NC, lon)) return 1;
  if (lat > lerp(B_CS, lon)) return 2;
  if (lon >= 36.5 && lat < lerp(B_SC, lon)) return 4;
  return 3;
}
