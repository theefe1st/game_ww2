const lerp = (P, x) => {
  if (x <= P[0][0]) return P[0][1];
  for (let k = 1; k < P.length; k++) if (x <= P[k][0]) { const [a, y0] = P[k - 1], [b, y1] = P[k]; return y0 + ((x - a) * (y1 - y0)) / (b - a); }
  return P[P.length - 1][1];
};
